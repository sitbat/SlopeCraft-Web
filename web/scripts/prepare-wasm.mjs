import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';

const directory=fileURLToPath(new URL('../wasm/',import.meta.url));
const wasm=await readFile(path.join(directory,'slopecraft.wasm'));
const module=await readFile(path.join(directory,'slopecraft.js'));
if(!WebAssembly.validate(wasm))throw new Error('Cannot compress an invalid WASM artifact');
const gzip=gzipSync(wasm,{level:9});
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const artifact={schemaVersion:1,wasmBytes:wasm.length,wasmSha256:sha(wasm),gzipBytes:gzip.length,gzipSha256:sha(gzip),moduleSha256:sha(module)};
await writeFile(path.join(directory,'slopecraft.wasm.gz'),gzip);
await writeFile(path.join(directory,'wasm-integrity.js'),`// Generated by prepare-wasm.mjs; do not edit.\nexport default ${JSON.stringify(artifact,null,2)};\n`);
console.log(`Prepared compressed WASM: ${wasm.length} → ${gzip.length} bytes (${(100*(1-gzip.length/wasm.length)).toFixed(1)}% smaller).`);
